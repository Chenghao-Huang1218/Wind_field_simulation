"""Seeded, grouped offline states; these are not flight measurements."""

from __future__ import annotations

import numpy as np
from numpy.typing import NDArray

FloatArray = NDArray[np.float64]


def body_to_world_rotation(quaternion: FloatArray) -> FloatArray:
    """Convert unit WXYZ quaternions to B→W rotation matrices.

    Args:
        quaternion: Unit WXYZ array [N,4].

    Returns:
        Proper rotation matrices [N,3,3].
    """
    quaternion = np.asarray(quaternion, dtype=np.float64)
    if (quaternion.ndim != 2 or quaternion.shape[1] != 4
            or not np.isfinite(quaternion).all()
            or not np.allclose(np.linalg.norm(quaternion, axis=1), 1,
                               atol=1e-8, rtol=0)):
        raise ValueError("Expected unit finite WXYZ [N,4]")
    scalar, axis_x, axis_y, axis_z = quaternion.T
    entries = (
        1 - 2*(axis_y**2 + axis_z**2), 2*(axis_x*axis_y - scalar*axis_z),
        2*(axis_x*axis_z + scalar*axis_y), 2*(axis_x*axis_y + scalar*axis_z),
        1 - 2*(axis_x**2 + axis_z**2), 2*(axis_y*axis_z - scalar*axis_x),
        2*(axis_x*axis_z - scalar*axis_y), 2*(axis_y*axis_z + scalar*axis_x),
        1 - 2*(axis_x**2 + axis_y**2),
    )
    return np.stack(entries, axis=-1).reshape(-1, 3, 3)


def sample_pilot_states(
    seed: int = 7, split_counts: tuple[int, int, int] = (2000, 500, 500),
) -> dict[str, NDArray]:
    """Sample independent 10-state groups, assigning whole groups to splits.

    Args:
        seed: Root SeedSequence seed; partitions have separate child streams.
        split_counts: Train, validation and diagnostic holdout sizes, multiples
            of ten. No formal training/test data are generated by this sampler.

    Returns:
        Numeric arrays with state, partition/group/sample IDs and seed.
        Train wind directions are 30° anchors, validation offset 15°, holdout
        offsets 7.5°/22.5°. Boundary states are independently drawn per split.
    """
    if len(split_counts) != 3 or any(n < 10 or n % 10 for n in split_counts):
        raise ValueError("Three split sizes must be positive multiples of ten")
    partitions = []
    group_offset = 0
    for split, (count, child_seed) in enumerate(zip(
            split_counts, np.random.SeedSequence(seed).spawn(3), strict=True)):
        rng = np.random.default_rng(child_seed)
        groups = count // 10
        local_group = np.arange(groups)
        if split == 0:
            speed = (local_group % 7) * 0.5
            offset = np.zeros(groups)
        elif split == 1:
            speed = np.array([0, .25, .75, 1.25, 1.75, 2.25, 2.75, 3])[local_group % 8]
            offset = np.full(groups, 15.)
        else:
            speed = rng.uniform(0, 3, groups)
            speed[local_group % 10 == 0] = 0
            speed[local_group % 10 == 1] = 3
            offset = np.where(local_group % 2 == 0, 7.5, 22.5)
        angle = np.deg2rad(30 * rng.integers(0, 12, groups) + offset)
        wind = np.repeat(np.column_stack((speed*np.cos(angle), speed*np.sin(angle),
                                         np.zeros(groups))), 10, axis=0)
        # Guard the exact 3 m/s domain against trigonometric roundoff.
        norm = np.linalg.norm(wind, axis=1)
        wind *= np.minimum(1, np.nextafter(3., 0.) / np.maximum(norm, 1e-300))[:, None]
        velocity_angle = rng.uniform(-np.pi, np.pi, count)
        velocity_speed = rng.uniform(0, 3, count)
        velocity = np.column_stack((velocity_speed*np.cos(velocity_angle),
                                    velocity_speed*np.sin(velocity_angle),
                                    rng.uniform(-1, 1, count)))
        hover = np.arange(count) % 10 == 1
        velocity[hover] *= 0.05
        opposing = (np.arange(count) % 10 == 2) & (np.linalg.norm(wind, axis=1) > 0)
        velocity[opposing, :2] = (
            -wind[opposing, :2] / np.linalg.norm(wind[opposing, :2], axis=1)[:, None]
            * velocity_speed[opposing, None]
        )
        euler = rng.uniform([-np.pi/9, -np.pi/9, -np.pi],
                            [np.pi/9, np.pi/9, np.pi], (count, 3))
        cosine = np.cos(euler / 2)
        sine = np.sin(euler / 2)
        cr, cp, cy = cosine.T
        sr, sp, sy = sine.T
        quaternion = np.column_stack((cr*cp*cy + sr*sp*sy, sr*cp*cy - cr*sp*sy,
                                      cr*sp*cy + sr*cp*sy, cr*cp*sy - sr*sp*cy))
        omega = rng.normal(size=(count, 3))
        omega /= np.linalg.norm(omega, axis=1, keepdims=True)
        omega *= (1.5 * rng.uniform(0, 1, count)**(1/3))[:, None]
        omega[np.arange(count) % 10 == 0] = 0
        partitions.append({
            "velocity_world": velocity, "quaternion_wxyz": quaternion,
            "rotation_body_to_world": body_to_world_rotation(quaternion),
            "euler_rpy_rad": euler, "omega_body": omega, "wind_world": wind,
            "split": np.full(count, split, dtype=np.int64),
            "group_id": np.repeat(local_group + group_offset, 10),
            "sampling_seed": np.full(count, seed, dtype=np.int64),
        })
        group_offset += groups
    data = {key: np.concatenate([part[key] for part in partitions])
            for key in partitions[0]}
    data["sample_id"] = np.arange(sum(split_counts), dtype=np.int64)
    return data
